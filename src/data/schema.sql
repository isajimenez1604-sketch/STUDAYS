create table if not exists public.users (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null unique,
  password_hash text not null,
  created_at    timestamptz not null default now()
);

-- Sin políticas: solo el backend (service role) puede leer/escribir
alter table public.users enable row level security;

create table if not exists public.tasks (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  title       text not null check (char_length(title) between 1 and 120),
  description text check (description is null or char_length(description) <= 1000),
  due_date    timestamptz,
  status      text not null default 'pending'
              check (status in ('pending', 'in_progress', 'completed', 'overdue')),
  created_at  timestamptz not null default now()
);

create index if not exists tasks_user_id_due_date_idx
  on public.tasks (user_id, due_date);

-- Sin políticas: solo el backend (service role) puede leer/escribir
alter table public.tasks enable row level security;

create table if not exists public.password_reset_codes (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  code_hash  text not null,
  expires_at timestamptz not null,
  used_at    timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists password_reset_codes_user_created_idx
  on public.password_reset_codes (user_id, created_at desc);

alter table public.password_reset_codes enable row level security;

create or replace function public.consume_password_reset(
  p_user_id bigint,
  p_code_hash text,
  p_password_hash text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.password_reset_codes
  set used_at = now()
  where user_id = p_user_id
    and code_hash = p_code_hash
    and used_at is null
    and expires_at > now();

  if not found then
    return false;
  end if;

  update public.users
  set password_hash = p_password_hash
  where id = p_user_id;

  return found;
end;
$$;

revoke all on function public.consume_password_reset(bigint, text, text)
  from public, anon, authenticated;
grant execute on function public.consume_password_reset(bigint, text, text)
  to service_role;
