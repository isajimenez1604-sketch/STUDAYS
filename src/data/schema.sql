create table if not exists public.users (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null unique,
  password_hash text not null,
  created_at    timestamptz not null default now()
);

-- Sin políticas: solo el backend (service role) puede leer/escribir
alter table public.users enable row level security;

create table if not exists public.tasks (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  title       text not null check (char_length(title) between 1 and 120),
  description text check (description is null or char_length(description) <= 1000),
  due_date    timestamptz,
  status      text not null default 'pending'
              check (status in ('pending', 'in_progress', 'completed', 'overdue')),
  created_at  timestamptz not null default now()
);

create index if not exists tasks_user_id_due_date_idx
  on public.tasks (user_id, due_date);

-- Sin políticas: solo el backend (service role) puede leer/escribir
alter table public.tasks enable row level security;

create table if not exists public.planner_intervals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 80),
  duration_minutes integer not null check (duration_minutes between 1 and 240),
  kind text not null check (kind in ('study', 'break')),
  created_at timestamptz not null default now()
);

create index if not exists planner_intervals_user_created_idx
  on public.planner_intervals (user_id, created_at, id);

alter table public.planner_intervals enable row level security;

create table if not exists public.password_reset_codes (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  code_hash  text not null,
  expires_at timestamptz not null,
  used_at    timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists password_reset_codes_user_created_idx
  on public.password_reset_codes (user_id, created_at desc);

alter table public.password_reset_codes enable row level security;

create table if not exists public.password_reset_email_limits (
  email_key         text primary key check (email_key ~ '^[0-9a-f]{64}$'),
  request_count     integer not null check (request_count between 1 and 5),
  blocked_until     timestamptz,
  updated_at        timestamptz not null default now()
);

create index if not exists password_reset_email_limits_updated_idx
  on public.password_reset_email_limits (updated_at);

alter table public.password_reset_email_limits enable row level security;

create or replace function public.consume_password_reset_email_attempt(
  p_email_key text
)
returns table(allowed boolean, retry_after_seconds integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := now();
  v_inserted integer;
  v_request_count integer;
  v_blocked_until timestamptz;
begin
  if p_email_key !~ '^[0-9a-f]{64}$' then
    raise exception 'Invalid password reset email key';
  end if;

  delete from public.password_reset_email_limits
  where updated_at < v_now - interval '24 hours';

  insert into public.password_reset_email_limits (
    email_key,
    request_count,
    updated_at
  )
  values (p_email_key, 1, v_now)
  on conflict (email_key) do nothing;

  get diagnostics v_inserted = row_count;
  if v_inserted = 1 then
    return query select true, 0;
    return;
  end if;

  select limits.request_count, limits.blocked_until
    into v_request_count, v_blocked_until
  from public.password_reset_email_limits as limits
  where limits.email_key = p_email_key
  for update;

  if v_blocked_until is not null then
    if v_blocked_until > v_now then
      return query
      select false, greatest(
        1,
        ceil(extract(epoch from (v_blocked_until - v_now)))::integer
      );
      return;
    end if;

    update public.password_reset_email_limits
    set request_count = 1,
        blocked_until = null,
        updated_at = v_now
    where email_key = p_email_key;

    return query select true, 0;
    return;
  end if;

  update public.password_reset_email_limits
  set request_count = v_request_count + 1,
      blocked_until = case
        when v_request_count + 1 = 5 then v_now + interval '15 minutes'
        else null
      end,
      updated_at = v_now
  where email_key = p_email_key;

  return query select true, 0;
end;
$$;

revoke all on function public.consume_password_reset_email_attempt(text)
  from public, anon, authenticated;
grant execute on function public.consume_password_reset_email_attempt(text)
  to service_role;

create or replace function public.consume_password_reset(
  p_user_id bigint,
  p_code_hash text,
  p_password_hash text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.password_reset_codes
  set used_at = now()
  where user_id = p_user_id
    and code_hash = p_code_hash
    and used_at is null
    and expires_at > now();

  if not found then
    return false;
  end if;

  update public.users
  set password_hash = p_password_hash
  where id = p_user_id;

  return found;
end;
$$;

revoke all on function public.consume_password_reset(bigint, text, text)
  from public, anon, authenticated;
grant execute on function public.consume_password_reset(bigint, text, text)
  to service_role;
