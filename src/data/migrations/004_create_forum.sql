
begin;

create table if not exists public.forum_posts (
  id bigint generated by default as identity primary key,
  user_id bigint not null
    references public.users(id) on delete cascade,
  title text not null
    check (char_length(trim(title)) between 1 and 150),
  content text not null
    check (char_length(trim(content)) between 1 and 5000),
  created_at timestamptz not null default now()
);

create table if not exists public.forum_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null
    references public.forum_posts(id) on delete cascade,
  user_id bigint not null
    references public.users(id) on delete cascade,
  content text not null
    check (char_length(trim(content)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists forum_posts_user_id_idx
  on public.forum_posts(user_id);

create index if not exists forum_comments_post_id_idx
  on public.forum_comments(post_id);

alter table public.forum_posts enable row level security;
alter table public.forum_comments enable row level security;

commit;
