begin;

create table if not exists public.planner_intervals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 80),
  duration_minutes integer not null check (duration_minutes between 1 and 240),
  kind text not null check (kind in ('study', 'break')),
  created_at timestamptz not null default now()
);

create index if not exists planner_intervals_user_created_idx
  on public.planner_intervals (user_id, created_at, id);

alter table public.planner_intervals enable row level security;

commit;
