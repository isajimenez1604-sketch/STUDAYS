-- Cambia tasks.id de UUID a BIGINT autoincremental y conserva las tareas existentes.
-- Ejecutar una sola vez en Supabase SQL Editor con el backend detenido.
begin;

alter table public.tasks
  add column id_new bigint generated by default as identity;

alter table public.tasks
  drop constraint tasks_pkey;

alter table public.tasks
  drop column id;

alter table public.tasks
  rename column id_new to id;

alter table public.tasks
  add constraint tasks_pkey primary key (id);

